const {chromium} = require("playwright");
const fs = require("node:fs");
const assert = require("node:assert/strict");
(async () => {
  const browser = await chromium.launch();
  const page = await browser.newPage({viewport: {width: 420, height: 900}});
  const errors = [];
  page.on("pageerror", error => errors.push(error.message));
  try {
    await page.setContent('<div id="root"></div>');
    await page.addStyleTag({path: "media/chat.css"});
    await page.evaluate(() => {
      window.requests = [];
      window.acquireVsCodeApi = () => ({getState: () => ({}), setState() {}, postMessage(data) {
        window.requests.push(data);
        setTimeout(() => {
          if (data.command === "getToolDetail") window.dispatchEvent(new MessageEvent("message", {data: {type: "toolDetail", requestId: data.messageId, stepIndex: data.stepIndex, toolInfo: {output: "expanded output " + data.stepIndex}, hasMore: false}}));
          if (data.command === "loadHistory") window.dispatchEvent(new MessageEvent("message", {data: {type: "historyPage", messages: Array.from({length: 30}, (_, index) => ({id: "earlier-" + index, role: "assistant", content: "Earlier " + index + "\n" + "long history text ".repeat(index * 3), timestamp: index - 30})), hasMore: false}}));
          window.dispatchEvent(new MessageEvent("message", {data: {type: "requestComplete", requestId: data.requestId, command: data.command}}));
        }, 0);
      }});
    });
    await page.addScriptTag({path: "media/chat.js"});
    const config = {autoScroll: false, defaultModel: "gemini-3.8-flash-high", reasoningEffort: "high"};
    const send = async (messages, hasMore = false) => page.evaluate(({messages, config, hasMore}) => window.dispatchEvent(new MessageEvent("message", {data: {type: "initSession", config, hasMore, session: {id: "virtual-session", title: "Virtual", model: "gemini-3.8-flash-high", effort: "high", messages}}})), {messages, config, hasMore});
    await send([{id: "tools", role: "assistant", status: "completed", content: "answer", toolCalls: Array.from({length: 10000}, (_, index) => ({stepIndex: index, name: "tool-" + index, state: "DONE", parameters: {index}, output: "preview"}))}]);
    await page.waitForSelector('[data-virtual-kind="tool"][data-virtual-total="10000"]');
    await page.waitForTimeout(150);
    const initialTools = await page.locator(".tool").count();
    assert(initialTools < 100, "tool DOM stays bounded at 10000 records");
    await page.locator('[data-virtual-key="0"] summary').click();
    await page.waitForFunction(() => document.querySelector('[data-virtual-key="0"]')?.textContent.includes("expanded output 0"));
    await page.evaluate(() => window.expanded = document.querySelector('[data-virtual-key="0"] details'));
    await page.locator(".messages").evaluate(element => element.scrollTop = element.scrollHeight);
    await page.waitForSelector('[data-virtual-key="9999"]');
    await page.waitForTimeout(150);
    await page.locator(".messages").evaluate(element => element.scrollTop = element.scrollHeight);
    await page.waitForTimeout(150);
    assert(await page.locator('[data-virtual-key="9999"]').evaluate(element => element.getBoundingClientRect().top < element.closest(".messages").getBoundingClientRect().bottom), "last tool is visible at the bottom");
    assert(await page.evaluate(() => window.expanded.isConnected && window.expanded.open), "expanded card remains mounted offscreen");
    const bottomTools = await page.locator(".tool").count();
    assert(bottomTools < 100);
    const toolAnchorBefore = await page.locator('[data-virtual-key="9999"]').evaluate(element => element.getBoundingClientRect().top);
    await page.locator('[data-virtual-key="0"] pre').last().evaluate(element => element.textContent += "\n" + "updated expanded output\n".repeat(100));
    await page.waitForTimeout(150);
    const toolAnchorAfter = await page.locator('[data-virtual-key="9999"]').evaluate(element => element.getBoundingClientRect().top);
    assert(Math.abs(toolAnchorBefore - toolAnchorAfter) <= 4, "offscreen expanded output resize preserves reading position");
    await page.locator(".messages").evaluate(element => element.scrollTop = 0);
    await page.waitForSelector('[data-virtual-key="1"]');
    await page.locator('[data-virtual-key="0"] summary').click();
    await page.locator('[data-virtual-key="1"] summary').evaluate(element => {
      const range = document.createRange();range.selectNodeContents(element);
      const selection = getSelection();selection.removeAllRanges();selection.addRange(range);
    });
    await page.waitForTimeout(100);
    const selected = await page.evaluate(() => getSelection().toString());
    await page.locator(".messages").evaluate(element => element.scrollTop = element.scrollHeight);
    await page.waitForSelector('[data-virtual-key="9999"]');
    assert.equal(await page.evaluate(() => getSelection().toString()), selected, "selected offscreen text is retained");
    await page.evaluate(() => getSelection().removeAllRanges());
    await page.locator(".messages").evaluate(element => element.scrollTop = 0);
    await page.waitForSelector('[data-virtual-key="2"] summary');
    await page.locator('[data-virtual-key="2"] summary').focus();
    await page.waitForTimeout(100);
    await page.locator(".messages").evaluate(element => element.scrollTop = element.scrollHeight);
    await page.waitForSelector('[data-virtual-key="9999"]');
    assert(await page.evaluate(() => document.activeElement?.closest('[data-virtual-key="2"]') !== null), "keyboard focus remains mounted offscreen");
    await page.locator("#message-input").focus();
    await send(Array.from({length: 1000}, (_, index) => ({id: "message-" + index, role: "assistant", status: "completed", content: "Message " + index + "\n" + "variable height ".repeat(index % 40), timestamp: index})), true);
    await page.locator(".messages").evaluate(element => element.scrollTop = 0);
    await page.waitForSelector('[data-virtual-key="message-0"]');
    await page.waitForTimeout(100);
    const mountedMessages = await page.locator(".message").count();
    assert(mountedMessages < 100);
    const beforeAnchor = await page.locator('[data-virtual-key="message-0"]').evaluate(element => element.getBoundingClientRect().top - element.closest(".messages").getBoundingClientRect().top);
    await page.locator("#load-history").click();
    await page.waitForSelector('[data-virtual-total="1030"][data-virtual-kind="message"]');
    await page.waitForTimeout(200);
    const afterAnchor = await page.locator('[data-virtual-key="message-0"]').evaluate(element => element.getBoundingClientRect().top - element.closest(".messages").getBoundingClientRect().top);
    assert(Math.abs(afterAnchor - beforeAnchor) <= 4, `history anchor is stable (${beforeAnchor} -> ${afterAnchor})`);
    await page.locator(".messages").evaluate(element => element.scrollTop = element.scrollHeight);
    await page.waitForSelector('[data-virtual-key="message-999"]');
    await page.waitForTimeout(150);
    await page.locator(".messages").evaluate(element => element.scrollTop = element.scrollHeight);
    await page.waitForTimeout(150);
    assert(await page.locator('[data-virtual-key="message-999"]').evaluate(element => element.getBoundingClientRect().top < element.closest(".messages").getBoundingClientRect().bottom), "last message is visible at the bottom");
    assert(await page.locator(".message").count() < 100);
    assert.equal(errors.length, 0);
    const report = {initialTools, bottomTools, mountedMessages, beforeAnchor, afterAnchor, toolAnchorBefore, toolAnchorAfter, expandedRetained: true, selectionRetained: true, focusRetained: true, lastMessageReachable: true, errors};
    fs.writeFileSync(process.env.AGY_VIRTUAL_OUTPUT || "diagnostics/optimization-virtual-browser.json", JSON.stringify(report, null, 2));
    console.log(report);
  } finally {await browser.close();}
})().catch(error => {console.error(error);process.exitCode = 1;});
